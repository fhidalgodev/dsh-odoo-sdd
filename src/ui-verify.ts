export interface UiLintFinding {
	rule: string;
	severity: "ERROR" | "WARN";
	message: string;
	flow?: string;
	step?: string;
}

/** The minimal plan-row shape the AC-coverage rule needs. */
export interface UiPlanRow {
	ac: string;
	layer: string;
}

const find = (severity: "ERROR" | "WARN", rule: string, message: string, flow?: string, step?: string): UiLintFinding => ({
	severity,
	rule,
	message,
	...(flow ? { flow } : {}),
	...(step ? { step } : {}),
});

/**
 * Structural lint of a flow set: unknown kinds, duplicate ids and missing
 * required payloads are ERRORs; a flow that only LOOKS (no verification or
 * action step) and a `ui` test-plan row no flow references are WARNs.
 */
export function lintUiFlows(flows: UiFlow[], planRows: UiPlanRow[] = []): UiLintFinding[] {
	const out: UiLintFinding[] = [];
	const flowIds = new Set<string>();
	const uiKinds = new Set<string>(UI_STEP_KINDS);
	const coveredAcs = new Set<string>();
	const LOOKS_ONLY = new Set(["goto", "menu", "screenshot", "explore", "wait"]);

	for (const flow of flows) {
		if (flow.id.trim() === "" || flowIds.has(flow.id)) {
			out.push(find("ERROR", "FLOW-ID", flow.id.trim() === "" ? "a flow has no id" : `flow id "${flow.id}" is duplicated`));
		}
		flowIds.add(flow.id);
		for (const ac of flow.ac ?? []) coveredAcs.add(ac);
		for (const [role, expected] of Object.entries(flow.roles ?? {})) {
			if (role.trim() === "") {
				out.push(find("ERROR", "ROLE-OUTCOME", `flow "${flow.id}" declares an empty roles key — every key must be a group xmlid`, flow.id));
			}
			if (expected !== "ok" && expected !== "denied") {
				out.push(find("ERROR", "ROLE-OUTCOME", `roles.${role} must be "ok" or "denied", got ${JSON.stringify(expected)}`, flow.id));
			}
		}
		if (flow.roles !== undefined && Object.keys(flow.roles).length > 0 && !flow.steps.some((s) => s.kind.startsWith("expect_"))) {
			out.push(
				find("WARN", "FLOW-ROLES-NO-EXPECT", `flow "${flow.id}" declares roles but has no expect_* step — a denied check alone cannot prove the page rendered`, flow.id),
			);
		}
		const stepIds = new Set<string>();
		let verifies = false;
		for (const step of flow.steps) {
			if (stepIds.has(step.id)) out.push(find("ERROR", "STEP-ID", `step id "${step.id}" is duplicated`, flow.id, step.id));
			stepIds.add(step.id);
			if (!uiKinds.has(step.kind)) {
				out.push(find("ERROR", "STEP-KIND", `unknown step kind "${step.kind}" (known: ${UI_STEP_KINDS.join(", ")})`, flow.id, step.id));
				continue;
			}
			if (step.kind === "drag" || step.kind === "highlight") {
				out.push(find("ERROR", "STEP-KIND", `${step.kind} steps belong to manuals/video, not to verification runs`, flow.id, step.id));
				continue;
			}
			if (!LOOKS_ONLY.has(step.kind)) verifies = true;
			const need = (cond: boolean, what: string): void => {
				if (cond) out.push(find("ERROR", "STEP-ARG", `${step.kind} needs ${what}`, flow.id, step.id));
			};
			switch (step.kind) {
				case "goto":
					need(step.target === undefined, "target");
					break;
				case "menu":
					need(step.target?.xmlid === undefined, "target.xmlid");
					break;
				case "fill":
				case "select":
					need(step.field === undefined, "field");
					need(step.value === undefined, "value");
					break;
				case "click":
					need(step.field === undefined, "field");
					break;
				case "wait":
				case "assert":
					need(step.value === undefined, "value");
					break;
				case "switch_view":
					need(step.view === undefined, "view");
					break;
				case "search":
				case "expect_state":
					need(step.value === undefined, "value");
					break;
				case "click_text":
					need(step.text === undefined, "text");
					break;
				case "expect_field":
					need(step.field === undefined, "field");
					need(step.value === undefined, "value");
					break;
				case "expect_visible":
				case "expect_hidden":
					need(step.field === undefined && step.text === undefined && step.value === undefined, "field, text or value");
					break;
				default:
					break;
			}
		}
		if (!verifies) {
			out.push(
				find("WARN", "FLOW-LOOKS-ONLY", `flow "${flow.id}" only navigates/screenshots — it verifies nothing (add an expect_*, assert or action step)`, flow.id),
			);
		}
	}
	for (const row of planRows) {
		if (/\bui\b/i.test(row.layer) && !coveredAcs.has(row.ac)) {
			out.push(find("WARN", "AC-UNCOVERED", `test-plan AC "${row.ac}" is declared at layer ui but no flow references it in ac[]`));
		}
	}
	return out;
}

/* ============================================================================
 * Role matrix — one temporary user per group, each running only the flows that
 * declare its expected outcome. User creation is a server mutation, so the
 * caller (the tool) resolves group xmlids, asks for human approval and only
 * then calls runUiMatrix; the runner never persists a password — it exists
 * only inside `accounts[].password` in memory.
 * ========================================================================== */

/** Message pattern that marks an "access denied" UI failure. */
const ACCESS_DENIED_RE = /access|acceso|访问|not allowed|AccessError/i;

/** Step kinds whose failing target can mean "the group cannot see it". */
const NAV_STEP_KINDS = new Set<UiStepKind>(["goto", "menu", "click", "open_row", "switch_view", "click_text"]);

/**
 * Classify a flow outcome against a DENIED expectation. The denial counts
 * only when the evidence is an access failure: an error dialog or JSON-RPC
 * error naming access, or a navigation/click step whose target was never
 * rendered (a menu or button the group cannot see). A clean run means the
 * role CAN do the flow; any other failure is a real defect, not the denied
 * path — both fail the expectation, but for different reasons.
 * @param steps - per-step results of the executed flow.
 * @returns "denied" on access evidence, "allowed" on a clean run, otherwise "other-error".
 */
export function classifyDenied(steps: UiStepResult[]): "denied" | "allowed" | "other-error" {
	let failed = false;
	for (const step of steps) {
		for (const finding of step.findings ?? []) {
			if ((finding.kind === "error-dialog" || finding.kind === "rpc-error") && ACCESS_DENIED_RE.test(finding.message)) {
				return "denied";
			}
		}
		if (step.status !== "error") continue;
		failed = true;
		const err = step.error ?? "";
		if (NAV_STEP_KINDS.has(step.kind) && (/no view rendered/i.test(err) || /Timeout.*exceeded/i.test(err) || /waiting for/i.test(err))) {
			return "denied";
		}
	}
	return failed ? "other-error" : "allowed";
}

export type UiMatrixVerdict = "PASSED" | "FAILED" | "PARTIAL" | "CLEANUP_PENDING" | "NEEDS_BROWSER" | "NOT_APPROVED";

/** One user the matrix will create, once approval is granted. */
export interface UiMatrixAccount {
	/** Group xmlid this account stands in for. */
	xmlid: string;
	/** Resolved res.groups id. */
	resId: number;
	/** Generated `sddqa_<n>_<rand4>` login — shown to the approver. */
	login: string;
}

export interface UiMatrixFlowResult {
	id: string;
	expected: "ok" | "denied";
	observed: "allowed" | "denied" | "other-error" | "not-run";
	pass: boolean;
	/** Why the expectation failed (e.g. "expected denied, but the flow ran"). */
	note?: string;
	steps: UiStepResult[];
	/** Findings the run attributed to this flow. */
	findings: number;
}

export interface UiMatrixGroupResult {
	group: string;
	resId: number;
	login: string;
	/** res.users id once created. */
	userId?: number;
	/** Authenticated uid of the web session. */
	uid?: number;
	/** Set when the per-user run could not start (login or browser failure). */
	error?: string;
	flows: UiMatrixFlowResult[];
}

export interface UiMatrixReport {
	schema: "dsh-odoo-sdd/ui-verify-matrix/1";
	mode: "matrix";
	verdict: UiMatrixVerdict;
	startedAt: string;
	serverVersion: string;
	environment?: string;
	flowsHash: string;
	ignore: string[];
	ignoredCount: number;
	groups: UiMatrixGroupResult[];
	createdUserIds: number[];
	cleanup: "none" | "deleted" | "archived" | "pending";
	error?: string;
}

export interface UiMatrixOptions {
	/** `<spec>/ui-verify/` — the report and per-user workspaces land here. */
	workspace: string;
	/** All declared flows; the matrix runs only those naming each group. */
	flows: UiFlow[];
	/** Accounts approved for creation (login already generated). */
	accounts: UiMatrixAccount[];
	/** res_id of `base.group_user` — every QA user is a portal-less internal user. */
	baseGroupId: number;
	/** `groups_id` pre-19, `group_ids` on 19 — from canon.groupsAttr. */
	groupsAttr: "groups_id" | "group_ids";
	browser: PwBrowser;
	family: UiFamily;
	executeKw: (model: string, method: string, args: unknown[], kwargs?: Record<string, unknown>) => Promise<RpcResult<unknown>>;
	/** Web login for a just-created user; cookie stays inside the session. */
	sessionAs: (login: string, password: string) => Promise<RpcResult<CaptureSession>>;
	/** Audit sink for user creation/cleanup — args must carry no secrets. */
	audit?: (op: string, args: unknown, extra?: { outcome?: "ok" | "error" | "denied"; reason?: string }) => void;
	serverVersion: string;
	environment?: string | null;
	allowActions?: boolean;
	ignore?: RegExp[];
	redact?: (text: string) => string;
	/** Injectable for tests; defaults to the real flow runner. */
	runFlows?: (opts: UiVerifyOptions) => Promise<RpcResult<UiVerifyReport>>;
}

/**
 * Create one temporary user per account, run each group's flows under its own
 * web session, and ALWAYS try to delete the users afterwards — unlink first,
 * `active: false` as the fallback. The generated passwords exist only in the
 * `secrets` map below; they are never written to the report, the audit trail
 * or any returned value. If the process dies between create and unlink the
 * `sddqa_*` users stay behind — the login prefix makes them identifiable.
 * @param opts - see {@link UiMatrixOptions}.
 * @returns the persisted matrix report.
 */
export async function runUiMatrix(opts: UiMatrixOptions): Promise<UiMatrixReport> {
	const startedAt = new Date().toISOString();
	const redact = opts.redact ?? ((t: string) => t);
	const runFlows = opts.runFlows ?? runUiFlows;
	const report: UiMatrixReport = {
		schema: "dsh-odoo-sdd/ui-verify-matrix/1",
		mode: "matrix",
		verdict: "FAILED",
		startedAt,
		serverVersion: opts.serverVersion,
		...(opts.environment ? { environment: opts.environment } : {}),
		flowsHash: createHash("sha256").update(JSON.stringify(opts.flows)).digest("hex"),
		ignore: (opts.ignore ?? []).map((re) => re.source),
		ignoredCount: 0,
		groups: [],
		createdUserIds: [],
		cleanup: "none",
	};

	// Passwords live only here, keyed by login, and are wiped before return.
	const secrets = new Map<string, string>();
	try {
		for (const account of opts.accounts) {
			const password = randomBytes(24).toString("base64url");
			const vals: Record<string, unknown> = {
				name: `SDD QA ${account.xmlid}`,
				login: account.login,
				password,
				[opts.groupsAttr]: [[6, 0, [opts.baseGroupId, account.resId]]],
			};
			const created = await opts.executeKw("res.users", "create", [vals], {
				context: { no_reset_password: true, tracking_disable: true },
			});
			if (!created.ok || typeof created.value !== "number") {
				report.error = redact(created.ok ? `res.users.create for ${account.login} returned no id` : created.error);
				throw new Error(report.error);
			}
			secrets.set(account.login, password);
			report.createdUserIds.push(created.value);
			report.groups.push({
				group: account.xmlid,
				resId: account.resId,
				login: account.login,
				userId: created.value,
				flows: [],
			});
		}
		if (report.createdUserIds.length > 0) {
			opts.audit?.("odoo_ui_verify/matrix-users", {
				users: report.groups.map((g) => ({ id: g.userId, login: g.login, group: g.group })),
			});
		}

		for (const group of report.groups) {
			const flows = opts.flows.filter((f) => f.roles?.[group.group] !== undefined);
			if (flows.length === 0) continue;
			const password = secrets.get(group.login) ?? "";
			const session = await opts.sessionAs(group.login, password);
			if (!session.ok) {
				group.error = redact(session.error);
				for (const f of flows) {
					group.flows.push({ id: f.id, expected: f.roles?.[group.group] ?? "ok", observed: "not-run", pass: false, steps: [], findings: 0 });
				}
				continue;
			}
			group.uid = session.value.uid;
			// Per-user workspace: images and its own run report stay evidence.
			const sub = `matrix-${group.login}`;
			const subRes = await runFlows({
				workspace: join(opts.workspace, sub),
				flows,
				session: session.value,
				browser: opts.browser,
				family: opts.family,
				serverVersion: opts.serverVersion,
				environment: opts.environment,
				allowActions: opts.allowActions === true,
				ignore: opts.ignore,
				redact,
			});
			if (!subRes.ok) {
				group.error = redact(subRes.error);
				for (const f of flows) {
					group.flows.push({ id: f.id, expected: f.roles?.[group.group] ?? "ok", observed: "not-run", pass: false, steps: [], findings: 0 });
				}
				continue;
			}
			const subReport = subRes.value;
			report.ignoredCount += subReport.ignoredCount;
			for (const flowRes of subReport.flows) {
				const flow = flows.find((f) => f.id === flowRes.id);
				const expected = flow?.roles?.[group.group] ?? "ok";
				const observed = classifyDenied(flowRes.steps);
				const pass = expected === "ok" ? observed === "allowed" : observed === "denied";
				const note =
					!pass && expected === "denied" && observed === "allowed"
						? "expected denied, but the flow ran"
						: !pass && expected === "denied" && observed === "other-error"
							? "expected denied, but the flow failed on non-access errors"
							: !pass && expected === "ok"
								? `expected ok, but the flow observed ${observed}`
								: undefined;
				// Point captures at the per-user subdir so paths stay valid.
				const steps = flowRes.steps.map((s) =>
					s.capture === undefined ? s : { ...s, capture: posixPath(join(sub, s.capture)) },
				);
				group.flows.push({ id: flowRes.id, expected, observed, pass, ...(note !== undefined ? { note } : {}), steps, findings: flowRes.findings });
			}
		}
	} catch (err) {
		if (report.error === undefined) report.error = redact(err instanceof Error ? err.message : String(err));
	} finally {
		secrets.clear();
		report.cleanup = await cleanupMatrixUsers(opts, report.createdUserIds);
		if (report.createdUserIds.length > 0) {
			opts.audit?.("odoo_ui_verify/matrix-cleanup", { ids: report.createdUserIds, cleanup: report.cleanup });
		}
	}

	const results = report.groups.flatMap((g) => g.flows);
	if (report.cleanup === "pending") {
		report.verdict = "CLEANUP_PENDING";
	} else if (report.error !== undefined) {
		// A run that died mid-way is never a pass — at best PARTIAL.
		report.verdict = results.some((f) => f.pass) ? "PARTIAL" : "FAILED";
	} else {
		const passed = results.filter((f) => f.pass).length;
		report.verdict = results.length > 0 && passed === results.length ? "PASSED" : passed === 0 ? "FAILED" : "PARTIAL";
	}
	writeFileAtomic(join(opts.workspace, "matrix-report.json"), JSON.stringify(report, null, "\t") + "\n");
	return report;
}

/**
 * Best-effort deletion of the temporary users: unlink, then archive. Both
 * failing leaves "pending" — the report's CLEANUP_PENDING verdict carries the
 * surviving ids so a human can remove them.
 * @param opts - matrix options (executeKw).
 * @param ids - res.users ids created by the run.
 * @returns the final cleanup state.
 */
async function cleanupMatrixUsers(opts: UiMatrixOptions, ids: number[]): Promise<UiMatrixReport["cleanup"]> {
	if (ids.length === 0) return "none";
	try {
		const unlinked = await opts.executeKw("res.users", "unlink", [ids]);
		if (unlinked.ok) return "deleted";
	} catch {
		// fall through to the archive attempt
	}
	try {
		const archived = await opts.executeKw("res.users", "write", [ids, { active: false }]);
		if (archived.ok) return "archived";
	} catch {
		// both failed
	}
	return "pending";
}
