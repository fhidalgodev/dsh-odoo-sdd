/**
 * ui-verify.ts — the verification runner behind `odoo_ui_verify`.
 *
 * `odoo_manual capture` photographs a flow; this runner VERIFIES it. Same
 * engine (`runStep`, the origin-locked context, the in-memory cookie), but
 * after EVERY step the UI probe is drained: an error dialog, a danger
 * notification, an invalid field, a js error or an RPC body with `error`
 * flips the step to `status: "error"` and freezes an `*-error.png` of what
 * the user actually saw. That is the difference between "the screen
 * rendered" and "the screen worked".
 *
 * On top of the base step vocabulary it adds verification-only steps
 * (open_row, switch_view, search, save, discard, click_text, add_line and
 * the `expect_*` assertions) resolved against the same versioned selector
 * families — never an invented selector.
 */
