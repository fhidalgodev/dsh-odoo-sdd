const UI_EXTRA_ACTION_KINDS: readonly UiStepKind[] = ["save", "discard", "click_text", "add_line"];
const UI_EXTRA_READ_KINDS: readonly UiStepKind[] = [
	"open_row",
	"switch_view",
	"search",
	"expect_state",
	"expect_field",
	"expect_visible",
	"expect_hidden",
];

/** Every kind the runner accepts (used by lint). */
export const UI_STEP_KINDS: readonly UiStepKind[] = [
	"goto",
	"menu",
	"new",
	"fill",
	"click",
	"select",
	"press",
	"drag",
	"wait",
	"confirm",
	"assert",
	"explore",
	"screenshot",
	"highlight",
	...UI_EXTRA_ACTION_KINDS,
	...UI_EXTRA_READ_KINDS,
];

/**
 * Effect classification of a step: `tab: true` pins a `click` to the notebook
 * tab (read-only by construction — it can never reach a header button), the
 * new kinds are fixed lists, and base kinds delegate to the manual model.
 */
export function uiStepSafety(step: Pick<UiStep, "kind" | "tab">): "read-only" | "action" {
	if (step.kind === "click" && step.tab === true) return "read-only";
	if ((UI_EXTRA_ACTION_KINDS as readonly string[]).includes(step.kind)) return "action";
	if ((UI_EXTRA_READ_KINDS as readonly string[]).includes(step.kind)) return "read-only";
	return stepSafety(step.kind as StepKind);
}

