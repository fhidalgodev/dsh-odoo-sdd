const slugify = (text: string): string =>
	text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40) || "menu";

function inventoriesOf(canon: Canon): CanonModule[] {
	return canon.modules ?? (canon.module ? [canon.module] : []);
}

/**
 * Generate the read-only smoke flows from a MODULE canon: for every menu that
 * opens an act_window, go to the menu, switch through every view type of the
 * view_mode, open the first record (when a list can show one) and visit every
 * notebook page of the model. Header buttons are never executed — only
 * `expect_visible`-checked when the canon declares them visible. Everything
 * the canon does not evidence produces no step.
 */
export function crawlFlowsFromCanon(canon: Canon): UiFlow[] {
	const flows: UiFlow[] = [];
	let n = 0;
	for (const inv of inventoriesOf(canon)) {
		const actionsByXmlid = new Map(
			inv.actions.filter((a) => a.xmlid !== undefined && a.kind === "ir.actions.act_window").map((a) => [a.xmlid as string, a]),
		);
		for (const menu of inv.menus) {
			if (!menu.xmlid || !menu.actionXmlid) continue;
			const action = actionsByXmlid.get(menu.actionXmlid);
			if (!action) continue;
			n += 1;
			let s = 0;
			const sid = (): string => `s${String((s += 1)).padStart(2, "0")}`;
			const steps: UiStep[] = [{ id: sid(), kind: "menu", target: { kind: "menu", xmlid: menu.xmlid } }];
			const viewTypes = (action.viewMode ?? "list").split(",").map((v) => v.trim()).filter((v) => v !== "");
			for (const view of viewTypes) steps.push({ id: sid(), kind: "switch_view", view });
			if (viewTypes.includes("form") && viewTypes.includes("list")) {
				steps.push({ id: sid(), kind: "open_row", index: 0 });
				const doc = inv.models.find((m) => m.model === (action.model ?? menu.model));
				for (const page of doc?.pages ?? []) {
					if (page.name) steps.push({ id: sid(), kind: "click", field: page.name, tab: true });
				}
				for (const b of doc?.buttons ?? []) {
					if (b.name === "" || b.invisibleRaw !== undefined) continue;
					steps.push({
						id: sid(),
						kind: "expect_visible",
						value: `.o_statusbar_buttons button[name="${b.name}"], header button[name="${b.name}"]`,
					});
				}
			}
			flows.push({ id: `crawl-${n}-${slugify(menu.completeName || menu.xmlid)}`, title: menu.completeName || menu.xmlid, steps });
		}
	}
	return flows;
}

