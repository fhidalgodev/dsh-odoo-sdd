export interface UiVerifyOptions {
	session: CaptureSession;
	browser: PwBrowser;
	family: UiFamily;
	flows: UiFlow[];
	/** What produced these flows: the QA-authored set, or the canon crawl. */
	mode?: "flows" | "crawl";
	/** Run only this flow id. */
	flow?: string;
	/** Resume `flow` from this step id after a failure. */
	fromStep?: string;
	allowActions: boolean;
	/** Keep going after a failing step (crawl forces it on). */
	continueOnError?: boolean;
	/** Caller-declared silence patterns (dropped but counted). */
	ignore?: RegExp[];
	/** Output redactor (the project secret scrubber by default). */
	redact?: (text: string) => string;
	/** Directory that receives report.json/crawl-report.json and images/. */
	workspace: string;
	serverVersion: string;
	environment?: string | null;
	/** sha256 of the flows source file when the tool already read it. */
	flowsHash?: string;
	signal?: AbortSignal;
}

const VIEWPORT = { width: 1440, height: 900 };

/**
 * Run the flows and write the report. A step error — runner failure OR probe
 * finding — stops the flow unless `continueOnError`; an AC only earns its
 * evidence line when its flow completed with zero findings.
 */
export async function runUiFlows(opts: UiVerifyOptions): Promise<RpcResult<UiVerifyReport>> {
	const mode = opts.mode ?? "flows";
	const selected = opts.flow === undefined ? opts.flows : opts.flows.filter((f) => f.id === opts.flow);
	if (opts.flow !== undefined && selected.length === 0) {
		return { ok: false, error: `flow ${opts.flow} is not in the flow set` };
	}
	if (selected.length === 0) return { ok: false, error: "no flows to run" };

	// Safety pre-check: one action step anywhere in the selected set needs the
	// explicit allow, exactly like captureFlow (tool and guard are two fences).
	let gated = false;
	for (const flow of selected) {
		let steps = flow.steps;
		if (opts.fromStep !== undefined && flow.id === opts.flow) {
			const idx = steps.findIndex((s) => s.id === opts.fromStep);
			if (idx < 0) return { ok: false, error: `from_step ${opts.fromStep} is not a step of flow ${flow.id}` };
			steps = steps.slice(idx);
		}
		if (steps.some((s) => uiStepSafety(s) === "action")) gated = true;
	}
	if (gated && !opts.allowActions) {
		return {
			ok: false,
			error:
				"the flow set contains ACTION steps (new/fill/select/press/click/save/discard/click_text/add_line) " +
				"but allow_actions is not true — read-only verification cannot run them",
		};
	}
	if (opts.fromStep !== undefined && opts.flow === undefined) {
		return { ok: false, error: "from_step needs flow: name the single flow to resume" };
	}

	const report: UiVerifyReport = {
		schema: "dsh-odoo-sdd/ui-verify/1",
		mode,
		verdict: "FAILED",
		startedAt: new Date().toISOString(),
		serverVersion: opts.serverVersion,
		...(opts.environment ? { environment: opts.environment } : {}),
		flowsHash: opts.flowsHash ?? createHash("sha256").update(JSON.stringify(selected)).digest("hex"),
		ignore: (opts.ignore ?? []).map((re) => re.source),
		ignoredCount: 0,
		originLocked: true,
		flows: [],
		evidence: {},
	};

	let context: PwContext | null = null;
	try {
		context = await opts.browser.newContext({ viewport: VIEWPORT });
		const baseUrl = opts.session.baseUrl.replace(/\/$/, "");
		// ORIGIN LOCK: abort everything that leaves the Odoo base URL — the same
		// fence captureFlow installs (requests off-origin abort by design, and
		// the probe already ignores those failures).
		await context.route("**/*", (route) => {
			const req = readShaped(route.request, route);
			const url = req.url();
			if (url.startsWith(baseUrl)) return route.continue();
			return route.abort();
		});
		const page = await context.newPage();
		const ctxWithCookies = context as unknown as { addCookies(cookies: unknown[]): Promise<void> };
		await ctxWithCookies.addCookies([{ name: "session_id", value: opts.session.sessionId, url: baseUrl }]);

		const imagesDir = join(opts.workspace, "images");
		mkdirSync(imagesDir, { recursive: true });
		const probe = attachProbe(page, opts.family, { baseUrl, ignore: opts.ignore, redact: opts.redact });

		const env: StepEnv = { baseUrl, imagesDir, slug: "", zoom: 1, recording: false };
		let aborted = false;
		for (const flow of selected) {
			const flowResult: UiFlowResult = { id: flow.id, title: flow.title, ac: flow.ac, status: "ok", steps: [], findings: 0 };
			env.slug = flow.id;
			let steps = flow.steps;
			if (opts.fromStep !== undefined && flow.id === opts.flow) {
				steps = steps.slice(steps.findIndex((s) => s.id === opts.fromStep));
			}
			for (const step of steps) {
				if (opts.signal?.aborted || aborted) {
					flowResult.steps.push({ id: step.id, kind: step.kind, status: "skipped", error: "aborted" });
					aborted = true;
					continue;
				}
				const result = await runUiStep(page, step, opts.family, env);
				// THE RULE: after every step, drain the probe. A screen that
				// rendered an error is a failing step even when the step itself
				// "worked" — this is the check captureFlow never had.
				const findings = await probe.drain();
				if (findings.length > 0) {
					flowResult.findings += findings.length;
					result.status = "error";
					result.findings = findings;
					result.error = `ui findings: ${findings.map((f) => `${f.kind} ${f.message}`).join(" | ").slice(0, 280)}`;
				}
				if (result.status === "error") {
					// Evidence of what the USER saw, frozen before the flow moves on.
					const capture = posixPath("images", `${flow.id}-${step.id}-error.png`);
					const shot = await page.screenshot({ type: "png" }).catch(() => null);
					if (shot !== null) {
						const dims = verifyPng(shot);
						if (dims.ok) {
							writeFileSync(join(imagesDir, `${flow.id}-${step.id}-error.png`), shot, { mode: 0o600 });
							result.capture = capture;
						}
					}
					flowResult.steps.push(result);
					flowResult.status = "error";
					if (opts.continueOnError !== true) break;
					continue;
				}
				flowResult.steps.push(result);
			}
			if (flowResult.steps.some((s) => s.status === "skipped")) flowResult.status = flowResult.status === "error" ? "error" : "skipped";
			report.flows.push(flowResult);
			if (aborted) break;
		}
		probe.dispose();
		report.ignoredCount = probe.ignoredCount();
		await page.close().catch(() => {});
		await context.close().catch(() => {});
		context = null;
	} catch (e) {
		return { ok: false, error: e instanceof Error ? e.message : String(e) };
	} finally {
		if (context) await context.close().catch(() => {});
	}

	// Verdict: every executed flow clean → PASSED; none clean → FAILED; a mix
	// → PARTIAL (a partial pass is still a failing verification, not a pass).
	const okCount = report.flows.filter((f) => f.status === "ok").length;
	report.verdict = okCount === report.flows.length ? "PASSED" : okCount === 0 ? "FAILED" : "PARTIAL";
	for (const flow of report.flows) {
		if (flow.status !== "ok") continue;
		for (const ac of flow.ac ?? []) {
			report.evidence[ac] = `pass (ui-verify ${flow.id}, ${flow.steps.length} steps, 0 UI errors)`;
		}
	}

	writeFileAtomic(join(opts.workspace, mode === "crawl" ? "crawl-report.json" : "report.json"), JSON.stringify(report, null, 2) + "\n");
	return { ok: true, value: report };
}

