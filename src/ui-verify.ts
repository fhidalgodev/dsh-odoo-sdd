/** The base vocabulary plus the verification-only steps. */
export type UiStepKind =
	| StepKind
	| "open_row"
	| "save"
	| "discard"
	| "switch_view"
	| "search"
	| "click_text"
	| "add_line"
	| "expect_state"
	| "expect_field"
	| "expect_visible"
	| "expect_hidden";

export interface UiStep {
	id: string;
	kind: UiStepKind;
	/** One-line description of what the step verifies (optional here). */
	procedure?: string | null;
	target?: Step["target"];
	/** Field name (fill/select/click/expect_field/add_line), button or tab name. */
	field?: string;
	value?: string;
	/** Row index for open_row (0-based; default 0). */
	index?: number;
	/** Visible text for click_text / expect_visible / expect_hidden. */
	text?: string;
	/** View type for switch_view (list, form, kanban…). */
	view?: string;
	/**
	 * `click` on a NOTEBOOK TAB only: resolves to the tab selector directly
	 * (never a header button), which keeps the step read-only. Generated by
	 * the canon crawl for each notebook page.
	 */
	tab?: boolean;
	/** Expected failure note (documentation, not behavior). */
	note?: string;
	/** Declared effect; "read-only" can never downgrade an action kind. */
	safety?: "read-only" | "action";
}

export interface UiFlow {
	id: string;
	title?: string;
	/** Acceptance criteria this flow proves (test-plan AC ids). */
	ac?: string[];
	steps: UiStep[];
	/** Expected outcome per role (parsed now, used by the role matrix). */
	roles?: Record<string, "ok" | "denied">;
}

