#!/usr/bin/env node
/**
 * Regenerate the voice preview samples embedded in `client/client.js`.
 *
 * The settings panel plays a short sample when a cloud voice preset is picked.
 * The browser half cannot call the plugin's server tools, and the host's
 * `/plugins/<package>/assets/` route serves images only, so the samples travel
 * inside the client bundle as `data:` URIs. Listening to one sends nothing
 * anywhere; only this maintainer script talks to Microsoft (edge-tts), with a
 * fixed sentence, once.
 *
 * The concrete voice and rate come from the compiled `lib/video-voices.js`
 * (`resolveVoiceEngine`), so a sample always uses the voice `odoo_video` would.
 * `tests/client.mjs` fails when the two drift.
 *
 * Requirements: `edge-tts` and `ffmpeg` on PATH, and `npm run build` first.
 * Usage: `node scripts/voice-samples.mjs`
 *
 * @module dsh-odoo-sdd/scripts/voice-samples
 */
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const clientPath = join(root, "client", "client.js");
const BEGIN = "/* voice-samples:begin";
const END = "/* voice-samples:end */";

/** The sentence each sample reads, per panel language. */
const SAMPLE_TEXT = {
	es: "Así sonará la narración de tus vídeos de Odoo.",
	en: "This is how your Odoo videos will sound.",
};
const { resolveVoiceEngine, VOICE_PRESETS } = await import(new URL("../lib/video-voices.js", import.meta.url).href);
/** Every cloud preset of the server catalog gets a sample. */
const CLOUD_PRESETS = VOICE_PRESETS.filter((preset) => preset.cloud).map((preset) => preset.id);

/**
 * Run a command without a shell and fail loudly on a non-zero exit.
 * @param {string[]} argv - program and arguments.
 */
function run(argv) {
	const result = spawnSync(argv[0], argv.slice(1), { encoding: "utf8" });
	if (result.error) throw new Error(`${argv[0]}: ${result.error.message}`);
	if (result.status !== 0) throw new Error(`${argv.join(" ")} exited ${result.status}\n${result.stderr}`);
}

const work = mkdtempSync(join(tmpdir(), "odoo-sdd-voices-"));
const samples = {};
try {
	for (const presetId of CLOUD_PRESETS) {
		samples[presetId] = {};
		for (const [lang, text] of Object.entries(SAMPLE_TEXT)) {
			const engine = resolveVoiceEngine({ ttsPreset: presetId, language: lang });
			if (!engine || !engine.cloud || !engine.voice) throw new Error(`no cloud voice for ${presetId}/${lang}`);
			const textFile = join(work, `${presetId}-${lang}.txt`);
			const raw = join(work, `${presetId}-${lang}.raw.mp3`);
			const out = join(work, `${presetId}-${lang}.mp3`);
			writeFileSync(textFile, text, "utf8");
			const argv = engine.command.split(/\s+/).map((token) =>
				token === "{textFile}" ? textFile : token === "{voice}" ? engine.voice : token === "{out}" ? raw : token,
			);
			run(argv);
			// Mono, 24 kHz, 24 kbit/s: a 3-second sample stays around 9 KB.
			run(["ffmpeg", "-v", "error", "-y", "-i", raw, "-ac", "1", "-ar", "24000", "-b:a", "24k", out]);
			samples[presetId][lang] = {
				voice: engine.voice,
				src: `data:audio/mpeg;base64,${readFileSync(out).toString("base64")}`,
			};
			console.log(`${presetId}/${lang}: ${engine.voice}`);
		}
	}
} finally {
	rmSync(work, { recursive: true, force: true });
}

const lines = Object.entries(samples).map(([presetId, byLang]) => {
	const langs = Object.entries(byLang).map(
		([lang, sample]) => `\t\t\t${lang}: { voice: ${JSON.stringify(sample.voice)}, src: ${JSON.stringify(sample.src)} }`,
	);
	return `\t\t${JSON.stringify(presetId)}: {\n${langs.join(",\n")}\n\t\t}`;
});
const block =
	`${BEGIN} — generated by scripts/voice-samples.mjs; do not edit by hand. */\n` +
	`\tvar VOICE_SAMPLES = {\n${lines.join(",\n")}\n\t};\n` +
	`\t${END}`;

const source = readFileSync(clientPath, "utf8");
const start = source.indexOf(BEGIN);
const end = source.indexOf(END);
if (start < 0 || end < start) throw new Error(`client.js has no ${BEGIN} … ${END} block`);
writeFileSync(clientPath, source.slice(0, start) + block + source.slice(end + END.length));
console.log(`client.js updated (${Math.round(Buffer.byteLength(block) / 1024)} KB of samples)`);
