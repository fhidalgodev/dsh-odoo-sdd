interface StepEnv {
	baseUrl: string;
	imagesDir: string;
	slug: string;
	zoom: number;
	recording: boolean;
}

const STEP_SETTLE_MS = 400;

async function runUiStep(page: PwPage, step: UiStep, family: UiFamily, env: StepEnv): Promise<UiStepResult> {
	const base: UiStepResult = { id: step.id, kind: step.kind, status: "ok" };
	const waitIdle = async (): Promise<void> => {
		await page.waitForSelector(family.selectors.loading, { state: "hidden", timeout: 15_000 }).catch(() => {});
		await page.waitForTimeout(STEP_SETTLE_MS).catch(() => {});
	};
	const textSelector = (scope: string, text: string): string => `${scope} >> text=${JSON.stringify(text)}`;
	try {
		switch (step.kind) {
			case "open_row": {
				const index = step.index ?? 0;
				await page.click(`${family.selectors.dataRow} >> nth=${index}`, { timeout: 10_000 });
				await waitIdle();
				break;
			}
			case "save": {
				await page.click(family.selectors.saveButton, { timeout: 10_000 });
				await waitIdle();
				break;
			}
			case "discard": {
				await page.click(family.selectors.discardButton, { timeout: 10_000 });
				await page.waitForSelector(family.selectors.modal, { state: "hidden", timeout: 5_000 }).catch(() => {});
				await waitIdle();
				break;
			}
			case "switch_view": {
				await page.click(family.selectors.switchView(step.view ?? ""), { timeout: 10_000 });
				await waitIdle();
				break;
			}
			case "search": {
				await page.fill(family.selectors.searchInput, step.value ?? "", { timeout: 10_000 });
				await page.press(family.selectors.searchInput, "Enter");
				await waitIdle();
				break;
			}
			case "click_text": {
				// The visible-text click stays inside the action manager or an open
				// modal — page furniture (navbar, chatter) is never a target.
				const text = step.text ?? "";
				const inModal = `${family.selectors.modal} >> text=${JSON.stringify(text)}`;
				const selector = (await page.$(inModal).catch(() => null)) ? inModal : textSelector(".o_action_manager", text);
				await page.click(selector, { timeout: 10_000 });
				await waitIdle();
				break;
			}
			case "add_line": {
				const selector = step.field ? `[name="${step.field}"] ${family.selectors.addRow}` : family.selectors.addRow;
				await page.click(selector, { timeout: 10_000 });
				await waitIdle();
				break;
			}
			case "expect_state": {
				const sel = `${family.selectors.statusbarCurrent}:text-is(${JSON.stringify(step.value ?? "")})`;
				await page.waitForSelector(sel, { state: "visible", timeout: 10_000 });
				break;
			}
			case "expect_field": {
				const sel = family.selectors.field(step.field ?? "");
				const actual = await page.evaluate(
					`(() => { const el = document.querySelector(${JSON.stringify(sel)}); if (!el) return null; ` +
						`const input = el.tagName === "INPUT" || el.tagName === "TEXTAREA" ? el : el.querySelector("input,textarea"); ` +
						`return (input ? input.value : el.textContent || "").trim(); })()`,
				);
				if (actual === null || String(actual).trim() !== (step.value ?? "").trim()) {
					return {
						...base,
						status: "error",
						error:
							actual === null
								? `expect_field ${step.field}: field not rendered (${sel})`
								: `expect_field ${step.field}: expected ${JSON.stringify(step.value ?? "")}, got ${JSON.stringify(String(actual).trim())}`,
					};
				}
				break;
			}
			case "expect_visible":
			case "expect_hidden": {
				const selectors = expectSelectors(step, family);
				if (selectors.length === 0) return { ...base, status: "error", error: `${step.kind} needs field, text or value (selector)` };
				if (step.kind === "expect_visible") {
					// ANY alternative on screen satisfies the expectation — a `,`
					// union cannot span two `>>` chains, so they are raced.
					await Promise.any(selectors.map((sel) => page.waitForSelector(sel, { state: "visible", timeout: 10_000 })));
				} else {
					// Hidden means NONE of the alternatives is on screen.
					await Promise.all(selectors.map((sel) => page.waitForSelector(sel, { state: "hidden", timeout: 10_000 })));
				}
				break;
			}
			default: {
				// Base vocabulary: delegate to the shared engine. A `click` pinned
				// to a notebook tab skips the header-button resolution entirely —
				// that is what keeps the step (and the crawl) read-only.
				if (step.kind === "click" && step.tab === true) {
					await page.click(family.selectors.notebookTab(step.field ?? ""), { timeout: 10_000 });
					await waitIdle();
					break;
				}
				const asStep: Step = { ...step, kind: step.kind as StepKind, procedure: step.procedure ?? null };
				const res: CaptureStepResult = await runStep(page, asStep, family, env);
				return { id: res.id, kind: res.kind, status: res.status, error: res.error, screenshot: res.screenshot, aria: res.aria };
			}
		}
		return base;
	} catch (e) {
		return { ...base, status: "error", error: e instanceof Error ? e.message : String(e) };
	}
}

/**
 * Selectors an `expect_*` step resolves (raw selector > field name > visible
 * text). Each entry is ONE locator chain: Playwright reads `,` inside a `>>`
 * chain as a sub-selector, not a union, so alternatives are raced/anded by the
 * caller instead of being joined.
 */
function expectSelectors(step: UiStep, family: UiFamily): string[] {
	if (step.field) return [`${family.selectors.headerButton(step.field)}, ${family.selectors.field(step.field)}, ${family.selectors.notebookTab(step.field)}`];
	if (step.text) return [`.o_action_manager >> text=${JSON.stringify(step.text)}`, `${family.selectors.modal} >> text=${JSON.stringify(step.text)}`];
	if (step.value) return [step.value];
	return [];
}

