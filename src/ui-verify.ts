export interface UiStepResult {
	id: string;
	kind: UiStepKind;
	status: "ok" | "error" | "skipped";
	error?: string;
	findings?: UiFinding[];
	screenshot?: { file: string; width: number; height: number; bytes: number };
	/** The automatic evidence shot of an error step (relative POSIX path). */
	capture?: string;
	aria?: string;
}

export interface UiFlowResult {
	id: string;
	title?: string;
	ac?: string[];
	status: "ok" | "error" | "skipped";
	steps: UiStepResult[];
	/** Total findings the run attributed to this flow. */
	findings: number;
}

export type UiVerifyVerdict = "PASSED" | "FAILED" | "PARTIAL" | "NEEDS_BROWSER";

export interface UiVerifyReport {
	schema: "dsh-odoo-sdd/ui-verify/1";
	/** "flows" runs the QA-authored flows.json; "crawl" runs the canon smoke. */
	mode: "flows" | "crawl";
	verdict: UiVerifyVerdict;
	startedAt: string;
	serverVersion: string;
	environment?: string;
	/** sha256 of the flows source (flows.json content, or the generated set). */
	flowsHash: string;
	/** The ignore patterns that were in force (a silence is a decision). */
	ignore: string[];
	ignoredCount: number;
	originLocked: true;
	flows: UiFlowResult[];
	/** AC id → suggested test-plan evidence line, only for flows that passed whole. */
	evidence: Record<string, string>;
}

type RpcResult<T> = { ok: true; value: T } | { ok: false; error: string; errorKind?: string };

